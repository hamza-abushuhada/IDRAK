CREATE SCHEMA IF NOT EXISTS idrak_lab_source;
CREATE SCHEMA IF NOT EXISTS idrak_lab_receiver;
CREATE TABLE IF NOT EXISTS idrak_lab_source.products (
  sku text PRIMARY KEY, name_ar text NOT NULL, name_en text NOT NULL,
  emoji text NOT NULL, price_mils integer NOT NULL, stock integer NOT NULL CHECK(stock>=0)
);
CREATE TABLE IF NOT EXISTS idrak_lab_source.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, external_id text UNIQUE,
  channel text NOT NULL, status text NOT NULL, payment_method text NOT NULL,
  customer text NOT NULL DEFAULT '', total_mils integer NOT NULL,
  inventory_applied integer NOT NULL DEFAULT 0, revision integer NOT NULL DEFAULT 1,
  created_at text NOT NULL, updated_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS idrak_lab_source.order_items (
  order_id bigint NOT NULL REFERENCES idrak_lab_source.orders(id), sku text NOT NULL,
  name_ar text NOT NULL, quantity integer NOT NULL, unit_price_mils integer NOT NULL
);
CREATE TABLE IF NOT EXISTS idrak_lab_source.source_events (
  seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, channel text NOT NULL,
  event_id text UNIQUE NOT NULL, event_type text NOT NULL, payload text NOT NULL,
  created_at text NOT NULL, attempts integer NOT NULL DEFAULT 0,
  delivered integer NOT NULL DEFAULT 0, last_error text
);
CREATE TABLE IF NOT EXISTS idrak_lab_receiver.received_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id text NOT NULL UNIQUE,
  source_id text NOT NULL, event_type text NOT NULL, payload text NOT NULL, received_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS idrak_lab_receiver.synced_orders (
  source_id text NOT NULL, external_id text NOT NULL, channel text NOT NULL,
  status text NOT NULL, total_mils integer NOT NULL, revision integer NOT NULL, updated_at text NOT NULL,
  PRIMARY KEY(source_id,external_id)
);
CREATE TABLE IF NOT EXISTS idrak_lab_receiver.synced_inventory (
  source_id text NOT NULL, sku text NOT NULL, stock integer NOT NULL,
  revision integer NOT NULL, updated_at text NOT NULL, PRIMARY KEY(source_id,sku)
);
CREATE INDEX IF NOT EXISTS lab_events_channel_cursor ON idrak_lab_source.source_events(channel,seq);
REVOKE ALL ON SCHEMA idrak_lab_source,idrak_lab_receiver FROM PUBLIC;
